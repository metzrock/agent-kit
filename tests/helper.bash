setup() {
  export KIT_ROOT
  KIT_ROOT=$(cd "$BATS_TEST_DIRNAME/.." && pwd)
  export HOME="$BATS_TEST_TMPDIR/home"
  mkdir -p "$HOME"
  unset CREW_IMPLEMENTER CREW_AGENT XDG_CACHE_HOME XDG_DATA_HOME CODEX_HOME
  unset CREW_IMPL_PROFILE CREW_CODEX_ARGS CREW_CODEX_AUTO_TRUST CREW_SONNET_NOTE
  unset AGENT_KIT_USAGE_CACHE CLOUD_CREDIT_UNTIL STATUSLINE_SHOW_DIR PROMPT_CLOCK_STALE_MIN PROMPT_CLOCK_LOW_AT
}
common() { source "$KIT_ROOT/lib/common.sh"; state_init; }
